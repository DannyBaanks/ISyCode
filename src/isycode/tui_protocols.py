def protocol_members(protocol: type) -> tuple[str, ...]:
    """Public-for-the-test introspection: the member methods a protocol pins."""
    return tuple(sorted(
        name for name, value in protocol.__dict__.items()
        if callable(value) and not isinstance(value, (classmethod, staticmethod))
    ))
