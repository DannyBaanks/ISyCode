"""Explicit cross-mixin interfaces for the TUI (F-05a).

The mixins collaborate through the app surface. These Protocols name the
methods each collaborating mixin exposes, so the boundary is a contract
instead of an accident of `self.*` reachability. M9 (mypy strict) will
enforce them; M8 asserts conformance at test time via the annotations.

The members mirror the measured cross-mixin call graph, not aspiration:
every name here is one mixin reaching into another today.
"""
from __future__ import annotations

from typing import Protocol


class SessionProvider(Protocol):
    """What the app's chat, tool, provider and rail layers need from sessions.

    Implemented by SessionMixin: lanes, persistence, queue/steering glue and
    the session-state queries other layers read.
    """

    def _active_lane(self): ...
    def _lane_on_screen(self) -> bool: ...
    def _ensure_lane_session(self) -> None: ...
    def _sessions_enabled(self) -> bool: ...
    def _persist_chat_message(self, role: str, content: str, *, sent_at: str | None = None) -> None: ...
    def _return_steering_to_queue(self, instructions, *, unsupported: bool = False) -> None: ...
    def _apply_idea_nudge(self, messages: list, chat_tools: list | None) -> None: ...
    def _mark_idea_nudge_due(self) -> None: ...
    def _paint_idea_box(self) -> None: ...
    def _paint_work_status(self) -> None: ...
    def _refresh_work_list(self) -> None: ...
    def _show_chat_again(self) -> None: ...
    def _session_state(self): ...
    def _session_is_diverged(self, session_id): ...
    def _active_chat_session_id(self): ...


class ChatController(Protocol):
    """What the session and tool layers need from the chat flow.

    Implemented by ChatMixin: the running turn and the transcript mounts.
    The turn's mutable buffers (`_active_chat_provider`, `_chat_turn_task`,
    `_batch_decisions`) are instance state, not protocol surface.
    """

    def _run_chat(self, text: str): ...
    def _mount_thought(self, title: str = "thinking..."): ...


class WorkspaceController(Protocol):
    """What the chat, tool, rail and authority layers need from the workspace.

    Implemented by WorkspaceMixin: owned requests, dispatch gates and the
    workspace capability queries.
    """

    def _workspace_request(self, action: str, target: str): ...
    def _workspace_read_owner(self): ...
    def _workspace_chat_tools_enabled(self) -> bool: ...
    def _workspace_write_tool_enabled(self) -> bool: ...
    def _command_tool_enabled(self) -> bool: ...
    def _file_action_enabled(self) -> bool: ...
    def _git_enabled(self) -> bool: ...
    def _session_trust_active(self) -> bool: ...
    def _dispatch_write_tool(self, call: dict): ...
    def _dispatch_file_change(self, call: dict): ...
    def _run_workspace_command(self, call: dict): ...
    def _git_tool(self, call: dict): ...
    def _confirm_and_load_external_context(self, call: dict): ...


PROTOCOLS = (SessionProvider, ChatController, WorkspaceController)


def protocol_members(protocol: type) -> tuple[str, ...]:
    """Public-for-the-test introspection: the member methods a protocol pins."""
    return tuple(sorted(
        name for name, value in protocol.__dict__.items()
        if callable(value) and not isinstance(value, (classmethod, staticmethod))
    ))
